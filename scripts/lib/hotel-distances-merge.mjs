/**
 * Pure merge logic for the hotel-distance generator. No network, no fs — so the
 * whole decision of "what to fetch" and "what the next file is" is unit-tested.
 */

/**
 * Which index slugs a run should fetch.
 * @param {{slug:string}[]} index - hotelIndex
 * @param {Record<string, {km:number|null, checked?:boolean}>} data - current hotelDistances
 * @param {{refresh?:boolean, only?:string}} opts
 * @returns {string[]}
 */
export function slugsToProcess(index, data, opts = {}) {
  if (opts.only) return index.some((h) => h.slug === opts.only) ? [opts.only] : [];
  return index
    .filter((h) => {
      const entry = data[h.slug];
      if (opts.refresh) return !(entry && entry.checked === true);
      // default: gap-fill — missing, or present but km not yet known
      return !entry || entry.km == null;
    })
    .map((h) => h.slug);
}

/**
 * Merge one fetch result into the data map, preserving checked:true rows.
 * The entry carries no district: the pricing region lives on the index row,
 * and a copy here would only make one unverified source look like two.
 * @param {object} data - current map (not mutated)
 * @param {{slug:string}} hotel
 * @param {{km:number, place:string} | null} result - null means no confident match
 * @returns {object} next map
 */
export function applyResult(data, hotel, result) {
  if (data[hotel.slug]?.checked === true) return data;
  const entry = result
    ? { km: result.km, place: result.place, checked: false }
    : { km: null, place: null, checked: false, note: "no-match" };
  return { ...data, [hotel.slug]: entry };
}

const bySlug = (data) => Object.entries(data).sort(([a], [b]) => a.localeCompare(b));

/**
 * Serialises the distance map into src/hotel-distances.js source text.
 *
 * The Place ID is left out on purpose. This module is imported by the booking
 * form, so every visitor downloads it; pricing needs the km and the checked
 * flag, while the Place ID is audit evidence that only the scripts read. It is
 * written to src/hotel-places.js instead — see renderHotelPlacesFile.
 */
export function renderHotelDistancesFile(data) {
  const sorted = Object.fromEntries(
    bySlug(data).map(([slug, { place: _place, ...row }]) => [slug, row]),
  );
  return `// Generated by scripts/build-hotel-distances.mjs — do not edit checked flags by hand.
// \`checked: true\` is written by scripts/audit-hotel-regions.mjs once the Place ID
// is identity-verified and its address agrees with the index region.
// One-way driving km from Antalya Airport (AYT) to each indexed hotel.
// Place IDs live in ./hotel-places.js: the browser prices on km, and only the
// audit scripts need the ID that proves which hotel a row was measured to.
export const hotelDistances = Object.freeze(${JSON.stringify(sorted, null, 2)});
`;
}

/** Serialises the audit-only Place IDs into src/hotel-places.js source text. */
export function renderHotelPlacesFile(data) {
  const sorted = Object.fromEntries(
    bySlug(data)
      .filter(([, row]) => row?.place)
      .map(([slug, row]) => [slug, row.place]),
  );
  return `// Generated by scripts/build-hotel-distances.mjs — do not edit by hand.
// The Google Place ID each row in ./hotel-distances.js was measured to, kept
// out of that file so the booking form does not ship it to every visitor.
export const hotelPlaces = Object.freeze(${JSON.stringify(sorted, null, 2)});
`;
}

/**
 * Rejoins the two generated files into the record the scripts work with.
 * @param {Record<string, object>} distances - hotelDistances
 * @param {Record<string, string>} places - hotelPlaces
 */
export function withPlaces(distances, places) {
  return Object.fromEntries(
    Object.entries(distances).map(([slug, row]) => {
      const place = places[slug];
      return [slug, place ? { ...row, place } : row];
    }),
  );
}

/** Builds a Routes API waypoint, preferring an already verified Place ID. */
export function routeDestination(hotel, geocoded) {
  if (hotel.placeId) return { placeId: hotel.placeId };
  return {
    location: {
      latLng: {
        latitude: geocoded.lat,
        longitude: geocoded.lng,
      },
    },
  };
}
