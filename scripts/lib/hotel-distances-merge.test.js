import { describe, test, expect } from "vitest";
import { slugsToProcess, applyResult, routeDestination, renderHotelDistancesFile, renderHotelPlacesFile, withPlaces } from "./hotel-distances-merge.mjs";

const index = [
  { slug: "a", name: "A Hotel", district: "Side" },
  { slug: "b", name: "B Hotel", district: "Belek" },
];

describe("slugsToProcess", () => {
  test("default run picks only slugs missing from the data or with null km", () => {
    const data = { a: { km: 50, checked: false } };
    expect(slugsToProcess(index, data, {})).toEqual(["b"]);
  });

  test("null-km rows are reprocessed on a default run", () => {
    const data = { a: { km: null }, b: { km: 40 } };
    expect(slugsToProcess(index, data, {})).toEqual(["a"]);
  });

  test("--refresh reprocesses all except checked:true rows", () => {
    const data = { a: { km: 50, checked: true }, b: { km: 40, checked: false } };
    expect(slugsToProcess(index, data, { refresh: true })).toEqual(["b"]);
  });

  test("--only limits to one slug", () => {
    const data = { a: { km: 50 }, b: { km: 40 } };
    expect(slugsToProcess(index, data, { only: "a" })).toEqual(["a"]);
  });
});

describe("applyResult", () => {
  test("writes km + place for a matched hotel, and no district", () => {
    const next = applyResult({}, { slug: "a", district: "Side" }, { km: 50, place: "p" });
    expect(next.a).toEqual({ km: 50, place: "p", checked: false });
  });

  test("writes km:null + note for a no-match", () => {
    const next = applyResult({}, { slug: "a", district: "Side" }, null);
    expect(next.a).toEqual({ km: null, place: null, checked: false, note: "no-match" });
  });

  test("never overwrites a checked:true row", () => {
    const data = { a: { km: 50, place: "p", checked: true } };
    const next = applyResult(data, { slug: "a", district: "Side" }, { km: 999, place: "q" });
    expect(next.a).toEqual(data.a);
  });
});

describe("renderHotelDistancesFile", () => {
  test("sorts slugs and emits a frozen export with the generator banner", () => {
    const file = renderHotelDistancesFile({ b: { km: 1, place: "y", checked: false }, a: { km: 2, place: "x", checked: true } });
    expect(file.startsWith("// Generated by scripts/build-hotel-distances.mjs")).toBe(true);
    expect(file.indexOf('"a"')).toBeLessThan(file.indexOf('"b"'));
    expect(file).toContain("export const hotelDistances = Object.freeze({");
    expect(file.endsWith("});\n")).toBe(true);
  });

  // Place IDs are audit evidence: the booking form prices on km and trusts a
  // row by its checked flag, so shipping 1246 opaque Google IDs to every
  // visitor only inflates the bundle.
  test("leaves the Place ID out of the module the browser loads", () => {
    const file = renderHotelDistancesFile({ a: { km: 2, place: "ChIJ-audit-only", checked: true } });
    expect(file).not.toContain("ChIJ-audit-only");
    expect(file).not.toContain('"place"');
    expect(file).toContain('"km": 2');
    expect(file).toContain('"checked": true');
  });

  test("keeps the no-match note, which the generator reads back", () => {
    const file = renderHotelDistancesFile({ a: { km: null, place: null, checked: false, note: "no-match" } });
    expect(file).toContain('"note": "no-match"');
  });
});

describe("renderHotelPlacesFile", () => {
  test("emits only the rows that have a Place ID, sorted", () => {
    const file = renderHotelPlacesFile({ b: { km: 1, place: "p-b" }, a: { km: 2, place: "p-a" }, c: { km: null, place: null } });
    expect(file).toContain("export const hotelPlaces = Object.freeze({");
    expect(file.indexOf('"a"')).toBeLessThan(file.indexOf('"b"'));
    expect(file).toContain('"a": "p-a"');
    expect(file).not.toContain('"c"');
  });
});

describe("withPlaces", () => {
  test("puts the audit Place ID back on the lean distance rows", () => {
    const merged = withPlaces({ a: { km: 2, checked: true } }, { a: "p-a" });
    expect(merged.a).toEqual({ km: 2, checked: true, place: "p-a" });
  });

  test("leaves a row without a recorded place untouched", () => {
    expect(withPlaces({ a: { km: 2, checked: false } }, {}).a).toEqual({ km: 2, checked: false });
  });
});

describe("routeDestination", () => {
  test("uses a discovered hotel's Place ID directly", () => {
    expect(routeDestination({ placeId: "place-123" })).toEqual({ placeId: "place-123" });
  });

  test("uses the geocoded coordinates for legacy index rows", () => {
    expect(routeDestination({}, { lat: 36.8, lng: 30.7 })).toEqual({
      location: { latLng: { latitude: 36.8, longitude: 30.7 } },
    });
  });
});
