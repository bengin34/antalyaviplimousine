/** Generates the reviewed discovery slice consumed by src/hotel-index.js. */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { mergeReviewedHotelMatches } from "./lib/hotel-index-discovered.mjs";

const input = fileURLToPath(new URL("./hotel-discovery-pilot/region-price-matches.json", import.meta.url));
const resolvedReviewInput = fileURLToPath(new URL("./hotel-discovery-pilot/region-review-resolved.json", import.meta.url));
const output = new URL("../src/hotel-index-discovered.js", import.meta.url);
const rows = mergeReviewedHotelMatches(
  JSON.parse(await readFile(input, "utf8")),
  JSON.parse(await readFile(resolvedReviewInput, "utf8")),
);

const districtLabels = {
  ALANYA: "Alanya",
  KEMER: "Kemer",
  KONYAALTI: "Konyaaltı",
  MANAVGAT: "Manavgat",
  MURATPAŞA: "Muratpaşa",
  SERİK: "Serik",
};

const generated = rows.map((row) => ({
  name: row.name,
  district: districtLabels[row.ministryDistricts[0]] ?? row.ministryDistricts[0],
  region: row.pricingRegion,
  placeId: row.placeId,
  ...(row.aliases?.length ? { aliases: row.aliases } : {}),
})).sort((left, right) => left.name.localeCompare(right.name, "tr"));

if (new Set(generated.map((row) => row.placeId)).size !== generated.length) {
  throw new Error("Discovered hotel Place IDs must be unique");
}

const file = `// Generated by scripts/generate-hotel-index-discovered.mjs from the safe\n`
  + `// region-price match set. Review rows are intentionally excluded.\n`
  + `export const discoveredHotelRows = Object.freeze(${JSON.stringify(generated, null, 2)});\n`;
await writeFile(output, file);
console.log(`Wrote ${generated.length} discovered hotels to ${fileURLToPath(output)}`);
