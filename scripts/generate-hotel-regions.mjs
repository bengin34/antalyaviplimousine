/**
 * Writes supabase/functions/_shared/hotel-regions.generated.ts: every indexed
 * hotel name (and alias), slugged, mapped to its pricing region.
 *
 * The edge function prices a Land of Legends excursion from the hotel's
 * region. It must not trust a region the browser sends — anyone could post a
 * cheaper one — so it resolves the region itself from the hotel name, using
 * this table. `src/land-of-legends-server.test.js` fails when the committed
 * file no longer matches the hotel index.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { hotelIndex, hotelSlug } from "../src/hotel-index.js";
import { landOfLegendsPrice } from "../src/land-of-legends.js";

// Two names for one slug in different regions: keep the dearer one, and a
// region with no fixed rate (quoted by hand) above any priced one.
const rank = (region) => landOfLegendsPrice(region, "vito") ?? Number.POSITIVE_INFINITY;

export function hotelRegionTable() {
  const table = new Map();
  for (const hotel of hotelIndex) {
    for (const name of [hotel.name, ...hotel.aliases]) {
      const slug = hotelSlug(name);
      if (!slug) continue;
      const current = table.get(slug);
      if (!current || rank(hotel.region) > rank(current)) table.set(slug, hotel.region);
    }
  }
  return Object.fromEntries([...table].sort(([a], [b]) => a.localeCompare(b)));
}

export function renderHotelRegionModule(table = hotelRegionTable()) {
  return `// Generated by scripts/generate-hotel-regions.mjs from src/hotel-index.js — do not edit.
// Hotel name slug → pricing region, for server-side Land of Legends pricing.
export const hotelRegionBySlug: Readonly<Record<string, string>> = ${JSON.stringify(table, null, 2)};
`;
}

export const hotelRegionModulePath = path.join(process.cwd(), "supabase", "functions", "_shared", "hotel-regions.generated.ts");

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(hotelRegionModulePath, renderHotelRegionModule());
  console.log(`Wrote ${Object.keys(hotelRegionTable()).length} hotel names to ${path.relative(process.cwd(), hotelRegionModulePath)}`);
}
